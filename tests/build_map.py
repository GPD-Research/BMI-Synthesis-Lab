"""Build viewer/map_data.js from the curated theory maps v2/map_v1.yaml and v2/map.yaml.

Each node's file/section is resolved to a line number so the viewer can open the file at the
section. Run `python3 tests/build_map.py` after editing a map; tests/check_map.py fails if the
generated file is stale.
"""
import json, os, re, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MAPS = [("v1", "v2/map_v1.yaml"), ("v2", "v2/map.yaml")]
OUT = "viewer/map_data.js"
REPO_URL = "https://github.com/GPD-Research/BMI-Synthesis-Lab"


def load(path):
    with open(os.path.join(ROOT, path), encoding="utf-8") as f:
        return yaml.safe_load(f)


def as_list(x):
    if x is None:
        return []
    return x if isinstance(x, list) else [x]


def heading_line(path, section):
    """1-based line of the heading that starts with `section` (e.g. '3.1a', 'R8', 'Pre-action layer')."""
    full = os.path.join(ROOT, path)
    if not os.path.isfile(full):
        return None
    pat = re.compile(r"^#+\s*(?:§\s*)?" + re.escape(section) + r"(?=[\s.:)]|$)")
    with open(full, encoding="utf-8") as f:
        for i, line in enumerate(f, 1):
            if pat.match(line):
                return i
    return None


def downstream_of_open(nodes):
    """Ids that depend, directly or through other boxes, on a link marked open or broken."""
    children = {}
    seeds = set()
    for n in nodes:
        for e in n.get("from", []):
            children.setdefault(e["id"], []).append(n["id"])
            if e["link"] in ("open", "broken"):
                seeds.add(n["id"])
    out, stack = set(), list(seeds)
    while stack:
        i = stack.pop()
        if i in out:
            continue
        out.add(i)
        stack.extend(children.get(i, []))
    return out


def build():
    data = {"repo": REPO_URL, "maps": {}}
    for version, path in MAPS:
        m = load(path)
        for n in m["nodes"]:
            n.setdefault("from", [])
            n["test"] = as_list(n.get("test"))
            if n.get("file") and n.get("section"):
                n["line"] = heading_line(n["file"], str(n["section"]))
        m["source"] = path
        m["conditional"] = sorted(downstream_of_open(m["nodes"]))
        m.setdefault("contradictions", [])
        data["maps"][version] = m
    return data


def render(data):
    body = json.dumps(data, ensure_ascii=False, indent=1, sort_keys=True)
    return ("// Generated by tests/build_map.py from v2/map_v1.yaml and v2/map.yaml. Do not edit.\n"
            "window.BMI_MAP = " + body + ";\n")


if __name__ == "__main__":
    text = render(build())
    with open(os.path.join(ROOT, OUT), "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {OUT}")
    sys.exit(0)
